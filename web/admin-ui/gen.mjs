// Bundles admin.html + admin.js (strategy editor) + shell.js (sidebar router, metrics, users, roles, clubs, cards, GPS, settings, audit)
// into lib/admin-assets.ts (served only to admins/editors by app/admin/[[...path]]/route.ts). Runs on prebuild.
import { readFileSync, writeFileSync } from "node:fs";
const dir = new URL(".", import.meta.url);
const js = ["confirm.js", "admin.js", "arclubs.js", "shell.js"].map(f => readFileSync(new URL(f, dir), "utf8")).join("\n");
if (/<\/script/i.test(js)) throw new Error("admin js must not contain a closing script tag");
const html = readFileSync(new URL("admin.html", dir), "utf8").replace("/*APP_JS*/", () => js);
const login = readFileSync(new URL("login.html", dir), "utf8");
writeFileSync(new URL("../lib/admin-assets.ts", dir), `// Generated by admin-ui/gen.mjs. Do not edit.\nexport const ADMIN_HTML = ${JSON.stringify(html)};\nexport const ADMIN_LOGIN_HTML = ${JSON.stringify(login)};\n`);
console.log("admin assets:", html.length, "bytes");
